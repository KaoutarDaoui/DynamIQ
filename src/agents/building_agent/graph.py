"""Agent 1 as a LangGraph agentic loop.

Turns the former one-shot pipeline (extract -> normalize -> persist) into a
loop that can notice low-confidence room extractions and dispatch follow-up
Groq calls (zoom, scale, adjacency, recount) before persisting, budgeted so
it can't loop forever.

Deviations from the original spec, made deliberately to match the *actual*
live system (verified against the real Supabase schema and the already-
shipped frontend contract this session — see repo history):

- ``rooms.building_id`` does not exist in the live `rooms` table (confirmed
  via a live query) — this graph never writes it. `Room` rows are scoped to
  a building only via `floor_id`.
- The frontend already sends a continuous compass angle, not a
  "top"/"bottom"/"left"/"right" string — the state field holding it is named
  `north_angle_deg` (not `north_direction`, which the original spec listed)
  to say honestly what it holds. `geometry_processor.compute_cardinal_orientations`
  already expects this float.
- `room_id` is generated by the existing, collision-safe
  `geometry_processor.auto_number_and_map_rooms` (`{building_id}-floor-{level}-room-{seq}`),
  not the spec's `{floor_level}{seq:02d}` scheme, which collides across
  buildings sharing a floor level (a real bug fixed earlier this session).
- Room-to-room adjacency isn't produced anywhere upstream (vision_processor
  and geometry_processor only know each room's own walls, not its
  neighbors). `_infer_bbox_adjacencies` below fills this gap with a simple
  geometric touching-bbox heuristic so `sanity_gate`'s adjacency check and
  the `room_adjacencies` persistence requirement have real data to work
  with, instead of being permanently inapplicable.
"""

