# ── geometric adjacency inference ────────────────────────────────────────
# geometry_processor only knows each room's own wall->cardinal mapping, not
# which room sits on the other side of a given wall. This fills that gap
# with a cheap touching-bbox heuristic in normalized image space.

_TOUCH_EPSILON = 0.02  # normalized units; bboxes within this gap count as touching


def _infer_bbox_adjacencies(rooms: list[dict[str, Any]]) -> list[tuple[str, str, str, float]]:
    """Return (room_id_a, room_id_b, direction_of_b_relative_to_a, overlap) for touching rooms.

    `overlap` (the shared-edge length) lets callers pick the strongest
    neighbor when a room touches more than one along the same side.
    """

    pairs: list[tuple[str, str, str, float]] = []
    for i, a in enumerate(rooms):
        ab = a["bbox"]
        ax0, ay0 = ab["x"], ab["y"]
        ax1, ay1 = ax0 + ab["width"], ay0 + ab["height"]
        for b in rooms[i + 1 :]:
            bb = b["bbox"]
            bx0, by0 = bb["x"], bb["y"]
            bx1, by1 = bx0 + bb["width"], by0 + bb["height"]

            vertical_overlap = min(ay1, by1) - max(ay0, by0)
            horizontal_overlap = min(ax1, bx1) - max(ax0, bx0)

            if vertical_overlap > 0 and abs(bx0 - ax1) <= _TOUCH_EPSILON:
                pairs.append((a["room_id"], b["room_id"], "east", vertical_overlap))
            elif vertical_overlap > 0 and abs(ax0 - bx1) <= _TOUCH_EPSILON:
                pairs.append((a["room_id"], b["room_id"], "west", vertical_overlap))
            elif horizontal_overlap > 0 and abs(by0 - ay1) <= _TOUCH_EPSILON:
                pairs.append((a["room_id"], b["room_id"], "south", horizontal_overlap))
            elif horizontal_overlap > 0 and abs(ay0 - by1) <= _TOUCH_EPSILON:
                pairs.append((a["room_id"], b["room_id"], "north", horizontal_overlap))

    return pairs


_OPPOSITE = {"north": "south", "south": "north", "east": "west", "west": "east"}


def _apply_adjacencies(rooms: list[dict[str, Any]]) -> None:
    """Write inferred neighbor room_ids into each room's config_json.adjacency, in place.

    A room can touch more than one neighbor along the same side (e.g. a
    large office bordering several smaller rooms) — resolve each
    (room, direction) slot to the single strongest (largest-overlap)
    neighbor first, instead of applying pairs in list order. Verified live:
    without this, whichever pair happened to be processed last silently
    overwrote an earlier one, leaving the discarded neighbor still pointing
    back — sanity_gate's adjacency_consistency check then flagged both
    rooms permanently, and no tool (least of all "zoom", which only
    touches area) could ever fix it, burning the whole retry budget.
    """

    by_id = {r["room_id"]: r for r in rooms}
    best: dict[tuple[str, str], tuple[str, float]] = {}
    for room_a_id, room_b_id, direction, overlap in _infer_bbox_adjacencies(rooms):
        a_key = (room_a_id, direction)
        if a_key not in best or overlap > best[a_key][1]:
            best[a_key] = (room_b_id, overlap)
        b_key = (room_b_id, _OPPOSITE[direction])
        if b_key not in best or overlap > best[b_key][1]:
            best[b_key] = (room_a_id, overlap)

    for (room_id, direction), (neighbor_id, _overlap) in best.items():
        room = by_id[room_id]
        room.setdefault("config_json", default_room_config())
        room["config_json"].setdefault("adjacency", {})[direction] = neighbor_id


# ── Groq helpers specific to this graph ──────────────────────────────────
# Vision calls reuse vision_processor's tuned request shape (downscale size,
# reasoning_effort="none", 429 retry) rather than re-deriving it — that
# tuning came from real rate-limit debugging earlier this session.


def _crop_room_bytes(file_bytes: bytes, filename: str, bbox: dict[str, float]) -> bytes:
    image = _load_source_image(file_bytes, filename)
    width, height = image.size
    x0 = max(0, int(bbox["x"] * width) - 10)
    y0 = max(0, int(bbox["y"] * height) - 10)
    x1 = min(width, int((bbox["x"] + bbox["width"]) * width) + 10)
    y1 = min(height, int((bbox["y"] + bbox["height"]) * height) + 10)
    crop = image.crop((x0, y0, x1, y1))
    buffer = io.BytesIO()
    crop.save(buffer, format="PNG")
    return buffer.getvalue()


def _call_groq_vision_json(image_bytes: bytes, prompt: str, api_key: str) -> dict[str, Any]:
    image_b64 = _downscale_to_base64_jpeg(image_bytes)
    raw_text = _call_groq_vision(image_b64, "image/jpeg", api_key, prompt=prompt)
    parsed = _parse_groq_response_object(raw_text)
    return parsed


def _parse_groq_response_object(raw_text: str) -> dict[str, Any]:
    """Like vision_processor._parse_groq_response, but for a single JSON object."""

    text = re.sub(r"<think>.*?</think>", "", raw_text, flags=re.DOTALL).strip()
    text = re.sub(r"```(?:json)?", "", text).strip()
    try:
        parsed = json.loads(text)
        if isinstance(parsed, dict):
            return parsed
    except json.JSONDecodeError:
        pass
    match = re.search(r"\{.*\}", text, re.DOTALL)
    if match:
        try:
            parsed = json.loads(match.group())
            if isinstance(parsed, dict):
                return parsed
        except json.JSONDecodeError:
            pass
    return {}


# Separate rate-limit budget from vision_processor's — this hits Groq's text
# model (llama-3.3-70b-versatile), not the vision model, so it has its own
# TPM allowance, but a busy minute can still 429 it just the same.
_DECISION_RATE_LIMIT_RETRIES = 5


def _call_groq_decision(prompt: str, api_key: str) -> dict[str, Any]:
    headers = {"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"}
    payload = {
        "model": DECISION_MODEL,
        "messages": [{"role": "user", "content": prompt}],
        "max_tokens": 400,
        "temperature": 0.1,
        "response_format": {"type": "json_object"},
    }
    with httpx.Client(timeout=60.0) as client:
        for attempt in range(_DECISION_RATE_LIMIT_RETRIES + 1):
            response = client.post(GROQ_API_URL, json=payload, headers=headers)

            if response.status_code == 429 and attempt < _DECISION_RATE_LIMIT_RETRIES:
                match = RETRY_AFTER_PATTERN.search(response.text)
                delay = float(match.group(1)) + 0.5 if match else 5.0
                logger.info("decide_action: rate limited, retrying in %.1fs", delay)
                time.sleep(delay)
                continue

            if response.is_error:
                raise ValueError(
                    f"Groq decision request failed with HTTP {response.status_code}: {response.text}"
                )

            content = response.json()["choices"][0]["message"]["content"]
            return _parse_groq_response_object(content)

    raise AssertionError("unreachable")  # loop always returns or raises


def _find_room(rooms: list[dict[str, Any]], room_id: str) -> dict[str, Any] | None:
    return next((r for r in rooms if r["room_id"] == room_id), None)


